/**
 * Scans assets/thumbnails/ and regenerates data/thumbnails.ts.
 *
 * Usage: from artifacts/photo-prompts run:  node scripts/gen-thumbnails.js
 *
 * Rule: name each image after the prompt id it belongs to, e.g.
 *   assets/thumbnails/portrait-studio-glow.webp
 * Accepted extensions: .webp .jpg .jpeg .png
 * Recommended: 800px wide, 4:3, webp, under 150 KB each.
 */
const fs = require('fs');
const path = require('path');

const THUMB_DIR = path.join(__dirname, '..', 'assets', 'thumbnails');
const OUT_FILE = path.join(__dirname, '..', 'data', 'thumbnails.ts');
const EXTS = ['.webp', '.jpg', '.jpeg', '.png'];

if (!fs.existsSync(THUMB_DIR)) fs.mkdirSync(THUMB_DIR, { recursive: true });

const files = fs
  .readdirSync(THUMB_DIR)
  .filter((f) => EXTS.includes(path.extname(f).toLowerCase()))
  .sort();

const entries = files
  .map((f) => {
    const id = path.basename(f, path.extname(f));
    return `  '${id}': require('../assets/thumbnails/${f}'),`;
  })
  .join('\n');

const content = `// AUTO-GENERATED by scripts/gen-thumbnails.js — do not edit by hand.
// Add images to assets/thumbnails/ named <prompt-id>.<ext>, then re-run the script.
import type { ImageSourcePropType } from 'react-native';

export const THUMBNAILS: Record<string, ImageSourcePropType> = {
${entries}
};

export function getThumbnail(promptId: string): ImageSourcePropType | undefined {
  return THUMBNAILS[promptId];
}
`;

fs.writeFileSync(OUT_FILE, content);
console.log(`thumbnails.ts generated with ${files.length} image(s).`);
