/**
 * Scans assets/thumbnails/ and regenerates data/thumbnails.ts.
 *
 * Usage: from artifacts/photo-prompts run:  node scripts/gen-thumbnails.js
 *
 * Two kinds of images are supported per prompt id:
 *   <id>.<ext>            -> single thumbnail (shown on the card + detail)
 *   <id>-before.<ext>     -> "before" image of a before/after pair
 *   <id>-after.<ext>      -> "after" image of a before/after pair
 *
 * If both -before and -after exist for an id, the detail screen shows an
 * interactive before/after slider, and the card shows the -after image.
 *
 * Accepted extensions: .webp .jpg .jpeg .png
 * Recommended: 800px wide, 4:3, webp, under 150 KB each.
 */
const fs = require('fs');
const path = require('path');

const THUMB_DIR = path.join(__dirname, '..', 'assets', 'thumbnails');
const OUT_FILE = path.join(__dirname, '..', 'data', 'thumbnails.ts');
const EXTS = ['.webp', '.jpg', '.jpeg', '.png'];

if (!fs.existsSync(THUMB_DIR)) fs.mkdirSync(THUMB_DIR, { recursive: true });

const files = fs
  .readdirSync(THUMB_DIR)
  .filter((f) => EXTS.includes(path.extname(f).toLowerCase()))
  .sort();

const singles = {};
const befores = {};
const afters = {};

for (const f of files) {
  const base = path.basename(f, path.extname(f));
  if (base.endsWith('-before')) {
    befores[base.slice(0, -'-before'.length)] = f;
  } else if (base.endsWith('-after')) {
    afters[base.slice(0, -'-after'.length)] = f;
  } else {
    singles[base] = f;
  }
}

const req = (f) => `require('../assets/thumbnails/${f}')`;

const thumbIds = new Set([...Object.keys(singles), ...Object.keys(afters)]);
const thumbEntries = [...thumbIds]
  .sort()
  .map((id) => {
    const f = singles[id] ?? afters[id];
    return `  '${id}': ${req(f)},`;
  })
  .join('\n');

const pairIds = Object.keys(befores).filter((id) => afters[id]).sort();
const pairEntries = pairIds
  .map(
    (id) =>
      `  '${id}': { before: ${req(befores[id])}, after: ${req(afters[id])} },`
  )
  .join('\n');

const content = `// AUTO-GENERATED by scripts/gen-thumbnails.js — do not edit by hand.
// Add images to assets/thumbnails/ then re-run: node scripts/gen-thumbnails.js
//   <id>.<ext>          single thumbnail
//   <id>-before.<ext>   + <id>-after.<ext>  interactive before/after slider
import type { ImageSourcePropType } from 'react-native';

export const THUMBNAILS: Record<string, ImageSourcePropType> = {
${thumbEntries}
};

export interface BeforeAfterPair {
  before: ImageSourcePropType;
  after: ImageSourcePropType;
}

export const BEFORE_AFTER: Record<string, BeforeAfterPair> = {
${pairEntries}
};

export function getThumbnail(promptId: string): ImageSourcePropType | undefined {
  return THUMBNAILS[promptId];
}

export function getBeforeAfter(promptId: string): BeforeAfterPair | undefined {
  return BEFORE_AFTER[promptId];
}
`;

fs.writeFileSync(OUT_FILE, content);
console.log(
  `thumbnails.ts generated: ${thumbIds.size} thumbnail(s), ${pairIds.length} before/after pair(s).`
);
